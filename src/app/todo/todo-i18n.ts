export function translate(
  locale: Locale,
  text: string,
  values: Record<string, string | number> = {},
) {
  const message = locale === "en" ? (english[text] ?? text) : text;
  // Replace placeholders in one pass; user content is never treated as a second template.
  return message.replace(/\{(\d+)\}/g, (token, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key)
      ? String(values[key])
      : token,
  );
}
export const localeTag = (locale: Locale) =>
  locale === "en" ? "en-US" : "vi-VN";
